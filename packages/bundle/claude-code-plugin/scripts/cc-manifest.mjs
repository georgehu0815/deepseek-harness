#!/usr/bin/env node
/**
 * cc-manifest.mjs — compose a profile for MULTIPLE Claude Code plugins at once.
 *
 * Build-order step 6. Generalizes the single-plugin install (step 5) to a
 * `pluginRoots[]` list. Every plugin's rows are namespaced by its plugin name so
 * commands, subagent tools, and MCP serverNames never collide across plugins:
 *   - command names  <- cc-commands pluginName = <plugin>            (=> /<plugin>-<cmd>)
 *   - subagent tools <- cc-subagents --namespace <plugin>            (=> <plugin>-<agent>)
 *   - MCP serverName <- cc-mcp --namespace <plugin>                  (=> mcp__<plugin>-<srv>__…)
 *   - skills         <- one shared skill-filesystem row with customSkillDirs = every <root>/skills
 *
 * The result is one profile cordis.patch.yml carrying, in a single `- insert:`:
 *   - one cc-skills row (all plugins' skills dirs)
 *   - one cc-commands row per plugin (each keyed to its own pluginRoot + pluginName)
 *   - one cc-hooks row per plugin that ships hooks/hooks.json
 *   - the namespaced mcp-client and tool-subagent rows for every plugin
 *
 * Because every id is plugin-namespaced, the rows are collision-free and the
 * whole profile is one reviewable file.
 *
 * Usage:
 *   node cc-manifest.mjs <manifest.json> <profileDir>
 * where manifest.json = { "plugins": [ { "root": "/abs/plugin", "name": "windows-brain" }, … ],
 *                         "provider": "spawn" }
 * `name` defaults to the plugin dir basename; `provider` defaults to spawn.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const MCP_GEN = join(HERE, 'cc-mcp-to-cordis.mjs')
const SUB_GEN = join(HERE, 'cc-subagents.mjs')

const [manifestPath, profileDir] = process.argv.slice(2)
if (!manifestPath || !profileDir) {
  console.error('usage: node cc-manifest.mjs <manifest.json> <profileDir>')
  process.exit(2)
}
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
const provider = manifest.provider ?? 'spawn'
const plugins = (manifest.plugins ?? []).map((p) => ({
  root: p.root,
  name: p.name ?? basename(p.root),
}))
if (plugins.length === 0) {
  console.error('manifest has no plugins')
  process.exit(1)
}

/** Sanitize a plugin name for use as an id/namespace segment. */
function ns(name) {
  return name.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/-{2,}/g, '-').replace(/^-+|-+$/g, '')
}

/** Run a generator, drop its `# comment` header lines, return the row block. */
function genRows(gen, args, guardPath) {
  if (guardPath && !existsSync(guardPath)) return ''
  return execFileSync('node', [gen, ...args], { encoding: 'utf8' })
    .split('\n').filter((l) => !l.startsWith('#')).join('\n').trim()
}

const blocks = []
let mcpTotal = 0
let subTotal = 0

// One shared skills row: every plugin's skills/ dir.
const skillDirs = plugins.map((p) => join(p.root, 'skills')).filter(existsSync)
if (skillDirs.length > 0) {
  blocks.push([
    `- id: cc-skills`,
    `  name: '@deepseek-ai/dsh-skill-filesystem'`,
    `  config:`,
    `    customSkillDirs:`,
    ...skillDirs.map((d) => `      - ${JSON.stringify(d)}`),
  ].join('\n'))
}

for (const p of plugins) {
  const n = ns(p.name)

  // Per-plugin commands loader (its own pluginRoot + namespaced command names).
  if (existsSync(join(p.root, 'commands'))) {
    blocks.push([
      `- id: cc-commands-${n}`,
      `  name: '@deepseek-ai/dsh-cc-commands'`,
      `  config:`,
      `    pluginRoot: ${JSON.stringify(p.root)}`,
      `    pluginName: ${n}`,
    ].join('\n'))
  }

  // Per-plugin hooks, only when the plugin ships them.
  if (existsSync(join(p.root, 'hooks', 'hooks.json'))) {
    blocks.push([
      `- id: cc-hooks-${n}`,
      `  name: '@deepseek-ai/dsh-hooks-claude-code'`,
      `  config:`,
      `    configPath: ${JSON.stringify(join(p.root, 'hooks', 'hooks.json'))}`,
      `    pluginRoot: ${JSON.stringify(p.root)}`,
    ].join('\n'))
  }

  // Namespaced MCP rows.
  const mcp = genRows(MCP_GEN, [join(p.root, '.mcp.json'), '--namespace', n], join(p.root, '.mcp.json'))
  if (mcp) { blocks.push(mcp); mcpTotal += (mcp.match(/^- id: mcp-/gm) ?? []).length }

  // Namespaced subagent rows.
  const sub = genRows(SUB_GEN, [p.root, '--provider', provider, '--namespace', n], join(p.root, 'agents'))
  if (sub) { blocks.push(sub); subTotal += (sub.match(/^- id: agent-/gm) ?? []).length }
}

const body = blocks.join('\n\n')
const indented = body.split('\n').map((l) => (l ? '    ' + l : l)).join('\n')
const patch = `# Generated by cc-manifest.mjs for ${plugins.length} Claude Code plugin(s).
# Every row is plugin-namespaced so commands, subagent tools, and MCP serverNames
# never collide across plugins. Applied as the profile's patch layer.
- insert:
${indented}
`

mkdirSync(profileDir, { recursive: true })
const target = join(profileDir, 'cordis.patch.yml')
writeFileSync(target, patch)

console.log(`wrote ${target}`)
console.log(`  ${plugins.length} plugin(s): ${plugins.map((p) => ns(p.name)).join(', ')}`)
console.log(`  ${skillDirs.length} skills dir(s), ${mcpTotal} mcp-client row(s), ${subTotal} tool-subagent row(s)`)
