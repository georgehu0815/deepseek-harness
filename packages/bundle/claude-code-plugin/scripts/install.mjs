#!/usr/bin/env node
/**
 * install.mjs — compose a profile's cordis.patch.yml for one Claude Code plugin.
 *
 * The dsh-claude-code-plugin BUNDLE carries the config-only rows (skills,
 * commands, hooks) keyed on CC_PLUGIN_ROOT. This script generates the
 * PER-PLUGIN rows that a static patch cannot express — one mcp-client row per
 * `.mcp.json` server (step 2) and one tool-subagent row per `agents/*.md`
 * (step 4) — and writes them as the PROFILE's own patch layer, applied after
 * the bundle with last-write-wins per id.
 *
 * Usage:
 *   node install.mjs <pluginRoot> <profileDir> [--provider spawn]
 *
 * Produces <profileDir>/cordis.patch.yml containing one `- insert:` of the
 * generated rows. Point the profile's dsh.profile.bundles at dsh-base and
 * dsh-claude-code-plugin, and set CC_PLUGIN_ROOT=<pluginRoot> at launch.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const MCP_GEN = join(HERE, 'cc-mcp-to-cordis.mjs')
const SUB_GEN = join(HERE, 'cc-subagents.mjs')

const [pluginRoot, profileDir] = process.argv.slice(2)
const provider = (() => {
  const i = process.argv.indexOf('--provider')
  return i !== -1 ? process.argv[i + 1] : 'spawn'
})()

if (!pluginRoot || !profileDir) {
  console.error('usage: node install.mjs <pluginRoot> <profileDir> [--provider spawn]')
  process.exit(2)
}
if (!existsSync(pluginRoot)) {
  console.error(`no plugin at ${pluginRoot}`)
  process.exit(1)
}

/** Run a generator; return its emitted rows with leading `# comment` lines dropped. */
function rows(genPath, args) {
  if (!existsSync(args[0])) return '' // no .mcp.json / no agents dir → no rows
  const out = execFileSync('node', [genPath, ...args], { encoding: 'utf8' })
  return out.split('\n').filter((l) => !l.startsWith('#')).join('\n').trim()
}

const mcpRows = rows(MCP_GEN, [join(pluginRoot, '.mcp.json')])
const subRows = rows(SUB_GEN, [pluginRoot, '--provider', provider])

const body = [mcpRows, subRows].filter(Boolean).join('\n\n')
const indented = body.split('\n').map((l) => (l ? '    ' + l : l)).join('\n')

const patch = `# Generated by dsh-claude-code-plugin/install.mjs for ${pluginRoot}
# Per-plugin MCP + subagent rows. Applied after the bundle layer (last write wins per id).
# Launch the profile with CC_PLUGIN_ROOT=${pluginRoot}.
- insert:
${indented}
`

mkdirSync(profileDir, { recursive: true })
const target = join(profileDir, 'cordis.patch.yml')
writeFileSync(target, patch)

const mcpCount = (mcpRows.match(/^- id: mcp-/gm) ?? []).length
const subCount = (subRows.match(/^- id: agent-/gm) ?? []).length
console.log(`wrote ${target}`)
console.log(`  ${mcpCount} mcp-client row(s), ${subCount} tool-subagent row(s), provider=${provider}`)
console.log(`  launch with CC_PLUGIN_ROOT=${pluginRoot}`)
